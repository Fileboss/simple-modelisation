import type { DataType } from '../data-types.ts';
import type { Mld } from './mld.ts';

export function postgresType(type: DataType): string {
	switch (type.kind) {
		case 'integer':
			return 'INTEGER';
		case 'bigint':
			return 'BIGINT';
		case 'decimal':
			return `NUMERIC(${type.precision},${type.scale})`;
		case 'text':
			return 'TEXT';
		case 'varchar':
			return `VARCHAR(${type.length})`;
		case 'boolean':
			return 'BOOLEAN';
		case 'date':
			return 'DATE';
		case 'datetime':
			return 'TIMESTAMP';
		case 'uuid':
			return 'UUID';
		case 'serial':
			return 'SERIAL';
	}
}

// PostgreSQL's reserved key words (also those reserved except as function or type names).
const RESERVED = new Set(
	`all analyse analyze and any array as asc asymmetric authorization binary both case cast check
	collate collation column concurrently constraint create cross current_catalog current_date
	current_role current_schema current_time current_timestamp current_user default deferrable desc
	distinct do else end except false fetch for foreign freeze from full grant group having ilike in
	initially inner intersect into is isnull join lateral leading left like limit localtime
	localtimestamp natural not notnull null offset on only or order outer overlaps placing primary
	references returning right select session_user similar some symmetric system_user table
	tablesample then to trailing true union unique user using variadic verbose when where window with`.split(
		/\s+/
	)
);

/** A name as PostgreSQL needs it: quoted when it is a reserved word. */
export const identifier = (name: string) => (RESERVED.has(name) ? `"${name}"` : name);

/** One piece of an MLD line; the UI underlines primary keys. */
export type MldPart = { text: string; primary: boolean };
export type MldLine = { table: string; parts: MldPart[] };

/**
 * The MLD in Looping's notation, one line per table:
 * `order = (id SERIAL, total NUMERIC(10,2), #customer_id*);` where `#` marks a
 * foreign key and `*` an optional one.
 */
export function mldLines(mld: Mld): MldLine[] {
	return mld.tables.map((table) => ({
		table: table.name,
		parts: table.columns.map((column) => ({
			text: column.foreign
				? `#${column.name}${column.nullable ? '*' : ''}`
				: `${column.name} ${postgresType(column.type)}`,
			primary: table.primaryKey.includes(column.name)
		}))
	}));
}

export function mldText(mld: Mld): string {
	return linesText(mldLines(mld));
}

export function linesText(lines: MldLine[]): string {
	return lines
		.map((line) => `${line.table} = (${line.parts.map((p) => p.text).join(', ')});`)
		.join('\n');
}

const list = (names: string[]) => names.map(identifier).join(', ');

/**
 * A string literal: quotes doubled. With a backslash, an escape string, which
 * reads the same whatever the database's standard_conforming_strings.
 */
const literal = (text: string) => {
	const quoted = `'${text.replace(/'/g, "''")}'`;
	return text.includes('\\') ? `E${quoted.replaceAll('\\', '\\\\')}` : quoted;
};

/**
 * A `--` comment on one line: a line break in a name (from a file or an agent)
 * would end the comment and leave the rest as SQL.
 */
const comment = (text: string) => `-- ${text.replace(/\s*[\n\r\v\f\u0085\u2028\u2029]+\s*/g, ' ')}`;

/** A constraint's name, quoted when PostgreSQL would read it otherwise (capitals, a reserved word). */
const constraintName = (name: string) => (/[A-Z]/.test(name) ? `"${name}"` : identifier(name));

/** The COMMENT ON statements: a paragraph per table. */
function commentsOn(mld: Mld): string[] {
	return mld.tables.flatMap((table) => {
		const name = identifier(table.name);
		const lines: string[] = [];
		if (table.comment) lines.push(`COMMENT ON TABLE ${name} IS ${literal(table.comment)};`);
		for (const column of table.columns.filter((c) => c.comment)) {
			lines.push(
				`COMMENT ON COLUMN ${name}.${identifier(column.name)} IS ${literal(column.comment!)};`
			);
		}
		for (const fk of table.foreignKeys.filter((f) => f.comment)) {
			lines.push(
				`COMMENT ON CONSTRAINT ${constraintName(fk.name!)} ON ${name} IS ${literal(fk.comment!)};`
			);
		}
		return lines.length > 0 ? [lines.join('\n')] : [];
	});
}

/**
 * The PostgreSQL script creating the MLD's tables. A foreign key to a table
 * created later (a cycle of references) is added by ALTER TABLE at the end.
 */
export function postgresScript(mld: Mld, title: string): string {
	const header = [comment(title), comment('Generated by Simple Modelisation.')];
	for (const warning of mld.warnings) header.push(comment(`Warning: ${warning}`));
	for (const note of mld.notes) header.push(comment(`Note: ${note}`));

	const created = new Set<string>();
	const deferred: string[] = [];
	const statements = mld.tables.map((table) => {
		created.add(table.name);
		const lines = table.columns.map((column) => {
			const notNull = !column.nullable && !table.primaryKey.includes(column.name);
			const type = postgresType(column.type);
			const check = column.check
				? ` CHECK (${identifier(column.name)} IN (${column.check.map(literal).join(', ')}))`
				: '';
			const condition = column.condition ? ` CHECK (${column.condition})` : '';
			return `   ${identifier(column.name)} ${type}${notNull && type !== 'SERIAL' ? ' NOT NULL' : ''}${check}${condition}`;
		});
		if (table.primaryKey.length > 0) lines.push(`   PRIMARY KEY (${list(table.primaryKey)})`);
		for (const columns of table.unique) lines.push(`   UNIQUE (${list(columns)})`);
		for (const fk of table.foreignKeys) {
			const clause = `CONSTRAINT ${constraintName(fk.name!)} FOREIGN KEY (${list(fk.columns)}) REFERENCES ${identifier(fk.table)} (${list(fk.references)})`;
			if (created.has(fk.table)) lines.push(`   ${clause}`);
			else deferred.push(`ALTER TABLE ${identifier(table.name)} ADD ${clause};`);
		}
		return `CREATE TABLE ${identifier(table.name)} (\n${lines.join(',\n')}\n);`;
	});

	return [header.join('\n'), ...statements, ...deferred, ...commentsOn(mld)].join('\n\n') + '\n';
}
